"use strict";
// electron-builder afterPack hook (wired via "afterPack" in package.json "build").
//
// Linux: puts a small POSIX sh launcher in front of the Electron binary: the real binary becomes
// "<executable>.bin" and "<executable>" is the script. The /usr/bin link and the .desktop file of the .deb, the
// AppImage's AppRun and the .tar.gz all start "<executable>", so one script covers all of them.
// Why a script: Chromium decides about its sandbox (and aborts as root) before any app JavaScript runs, so
// main.js cannot fix that. The launcher:
//  - command line use (first argument run / echo-server / help / --help / --version / --cli) or no graphical
//    display: runs src/cli.js with Electron's built-in Node.js (ELECTRON_RUN_AS_NODE), so no Chromium processes
//    (sandbox, zygote, GPU) are started at all - works on servers, in CI and over SSH.
//  - otherwise: starts the desktop app WITH the Chromium sandbox whenever this system can run it. It is turned
//    off (one line on stderr, and API_TESTER_SANDBOX_DISABLED=<reason> for the app's log) only when it cannot
//    work: running as root; no usable user namespaces (`unshare -Ur true` fails: containers, Ubuntu 23.10+'s
//    AppArmor restriction for programs without a profile - the AppImage / .tar.gz there) and neither the .deb's
//    AppArmor profile (build/linux/apparmor-profile.tpl, grants "userns") nor a root-owned SUID chrome-sandbox
//    applies (the SUID helper cannot be started from a path with a space, like "/opt/API Tester"); or when the
//    user asks for it (--no-sandbox, API_TESTER_DISABLE_SANDBOX=1).
//  - checks for missing shared libraries first (minimal server / container images) and prints the exact
//    apt / dnf command instead of a bare "error while loading shared libraries" or SIGTRAP.
//
// Electron fuses (package.json "build.electronFuses"): electron-builder flips them right after this hook, on
// "<appOutDir>/<executable>" - on Linux that is the launcher script by then. afterPackLinux therefore points
// electron-builder's fuse step at "<executable>.bin" (and checks the result). RunAsNode stays enabled: the
// launcher's command line mode and the macOS / Windows CLI wrappers (build/bin) run src/cli.js with
// ELECTRON_RUN_AS_NODE. NODE_OPTIONS, --inspect and loading the app from outside app.asar are switched off.
//
// macOS: makes sure the CLI wrapper Contents/Resources/bin/api-tester is executable and that Electron's and
// Chromium's licence notices are in Contents/Resources.
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

/** Quotes a value for use inside a double-quoted sh string. */
function shDq(value) {
    return String(value).replace(/[\\"$`]/g, "\\$&");
}

/**
 * Returns the launcher script.
 * binName: file name of the real Electron binary; cliPath: cli.js relative to the app folder;
 * productName: shown in messages; profileName: name of the .deb's AppArmor profile (the executable name).
 */
function launcherScript({ binName, cliPath, productName, profileName }) {
    return `#!/bin/sh
# ${productName} launcher, generated by build/afterPack.js. The real Electron binary is ${binName}.
#   api-tester run <suite> ... / echo-server / --help: command line version (Electron's built-in Node.js)
#   no graphical display: command line version as well
#   otherwise: desktop app, with the Chromium sandbox unless this system cannot run it (see sandbox_problem)
SELF="$(readlink -f "$0" 2>/dev/null)"
[ -n "$SELF" ] || SELF="$0"
HERE="$(cd "$(dirname "$SELF")" && pwd -P)"
BIN="$HERE/${shDq(binName)}"

# Chromium switches are skipped when looking for the command: the AppImage's AppRun puts --no-sandbox first
is_switch() {
    case "$1" in --no-sandbox|--disable-gpu|--disable-gpu-sandbox|--in-process-gpu|--disable-dev-shm-usage) return 0 ;; esac
    return 1
}
FIRST=""
NARGS=0
for ARG in "$@"; do
    is_switch "$ARG" && continue
    NARGS=$((NARGS + 1))
    if [ -z "$FIRST" ]; then FIRST="$ARG"; fi
done

MODE=gui
case "$FIRST" in
    run|echo-server|help|--help|-h|--version|-v|--cli) MODE=cli ;;
esac
for ARG in "$@"; do
    if [ "$ARG" = "--cli" ]; then MODE=cli; fi
done
if [ "$MODE" = gui ] && [ -z "$DISPLAY" ] && [ -z "$WAYLAND_DISPLAY" ]; then
    if [ "$NARGS" -eq 0 ]; then
        echo "No graphical display found (DISPLAY / WAYLAND_DISPLAY not set) - showing the command line version." >&2
    fi
    MODE=cli
fi
# a local X display that does not exist (stale DISPLAY over SSH, sudo): say so instead of Chromium's errors
if [ "$MODE" = gui ] && [ -z "$WAYLAND_DISPLAY" ]; then
    case "$DISPLAY" in
        :[0-9]*)
            XNUM="\${DISPLAY#:}"
            XNUM="\${XNUM%%.*}"
            if [ ! -S "/tmp/.X11-unix/X$XNUM" ]; then
                echo "Cannot reach the X display $DISPLAY - showing the command line version (use --cli, or fix DISPLAY / X forwarding)." >&2
                MODE=cli
            fi
            ;;
    esac
fi

# true when a shared library can be found; dlopen()ed libraries do not show up in ldd
have_lib() {
    OLD_IFS="$IFS"; IFS=:
    for DIR in $LD_LIBRARY_PATH; do
        if [ -n "$DIR" ] && [ -e "$DIR/$1" ]; then IFS="$OLD_IFS"; return 0; fi
    done
    IFS="$OLD_IFS"
    for DIR in /usr/lib/*-linux-gnu /lib/*-linux-gnu /usr/lib64 /lib64 /usr/lib /lib /usr/local/lib; do
        if [ -e "$DIR/$1" ]; then return 0; fi
    done
    # /sbin is not in a normal user's PATH on Debian
    for LDCONFIG in ldconfig /sbin/ldconfig /usr/sbin/ldconfig; do
        if command -v "$LDCONFIG" >/dev/null 2>&1; then
            "$LDCONFIG" -p 2>/dev/null | grep -q "$1" && return 0
            break
        fi
    done
    return 1
}

# ALSA package name: libasound2t64 on Ubuntu 24.04+ / Debian 13+ (64-bit time_t transition)
alsa_package() {
    if command -v apt-cache >/dev/null 2>&1 && apt-cache show libasound2t64 >/dev/null 2>&1; then
        echo libasound2t64; return
    fi
    ID=""; VERSION_ID=""
    if [ -r /etc/os-release ]; then . /etc/os-release; fi
    case "$ID" in
        ubuntu) if [ "\${VERSION_ID%%.*}" -ge 24 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
        debian) if [ "\${VERSION_ID%%.*}" -ge 13 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
    esac
    echo libasound2
}

# the Electron binary links these libraries even when it only runs as Node.js (command line version)
if command -v ldd >/dev/null 2>&1; then
    MISSING="$(ldd "$BIN" 2>/dev/null | sed -n 's/^[[:space:]]*\\([^[:space:]]*\\) => not found.*/\\1/p' | sort -u | tr '\\n' ' ')"
    if [ "$MODE" = gui ] && ! have_lib libX11-xcb.so.1; then MISSING="\${MISSING}libX11-xcb.so.1 "; fi
    if [ -n "$MISSING" ]; then
        # root (e.g. a minimal container) usually has no sudo
        SUDO="sudo "
        if [ "$(id -u)" = 0 ]; then SUDO=""; fi
        {
            echo "${shDq(productName)} cannot start, these system libraries are missing: $MISSING"
            echo "Install them and start again:"
            echo "  Debian/Ubuntu: \${SUDO}apt-get update && \${SUDO}apt-get install -y libgtk-3-0 libnss3 $(alsa_package) libgbm1 libx11-xcb1 libxss1 libxtst6 libatspi2.0-0 libsecret-1-0 libnotify4 xdg-utils"
            echo "  Fedora/RHEL:   \${SUDO}dnf install -y gtk3 nss alsa-lib mesa-libgbm libX11-xcb libXScrnSaver libXtst at-spi2-core libsecret libnotify xdg-utils"
            echo "Or run suites without the app: the Docker image or Node.js 22.13+ (node src/cli.js run ...)."
        } >&2
        exit 2
    fi
fi

if [ "$MODE" = cli ]; then
    # the command line version does not take Chromium switches
    for ARG in "$@"; do
        shift
        is_switch "$ARG" || set -- "$@" "$ARG"
    done
    export ELECTRON_RUN_AS_NODE=1
    exec "$BIN" "$HERE/${shDq(cliPath)}" "$@"
fi

# Prints why the Chromium sandbox cannot work here; prints nothing when it can (the normal case).
sandbox_problem() {
    case "$API_TESTER_DISABLE_SANDBOX" in ""|0|false|no) ;; *) echo "API_TESTER_DISABLE_SANDBOX is set"; return ;; esac
    # Chromium refuses to start as root with its sandbox
    if [ "$(id -u)" = 0 ]; then echo "running as root"; return; fi
    # unprivileged user namespaces (Chromium's normal sandbox) work
    if command -v unshare >/dev/null 2>&1 && unshare -Ur true >/dev/null 2>&1; then return; fi
    # Ubuntu 23.10+: unshare runs without a profile and is blocked, but the .deb's AppArmor profile allows user
    # namespaces for this app (it applies to this script and to the binary)
    LABEL=""
    if [ -r /proc/self/attr/apparmor/current ]; then read -r LABEL < /proc/self/attr/apparmor/current 2>/dev/null
    elif [ -r /proc/self/attr/current ]; then read -r LABEL < /proc/self/attr/current 2>/dev/null; fi
    case "$LABEL" in "${shDq(profileName)}"|"${shDq(profileName)} "*) return ;; esac
    # no user namespaces: Chromium's setuid helper (root-owned, mode 4755), which cannot start from a path with a space
    case "$HERE" in
        *" "*) ;;
        *) if [ -u "$HERE/chrome-sandbox" ] && [ "$(stat -c %u "$HERE/chrome-sandbox" 2>/dev/null)" = 0 ]; then return; fi ;;
    esac
    echo "user namespaces are not available or are blocked on this system"
}

unset ELECTRON_RUN_AS_NODE
NO_SANDBOX=""
for ARG in "$@"; do
    if [ "$ARG" = "--no-sandbox" ]; then NO_SANDBOX="requested with --no-sandbox"; fi
done
[ -n "$NO_SANDBOX" ] || NO_SANDBOX="$(sandbox_problem)"
if [ -n "$NO_SANDBOX" ]; then
    # one line for the terminal / system journal; the app writes the reason into its own log
    echo "${shDq(productName)}: Chromium sandbox disabled ($NO_SANDBOX). See SECURITY.md (Linux sandbox)." >&2
    export ELECTRON_DISABLE_SANDBOX=1
    export API_TESTER_SANDBOX_DISABLED="$NO_SANDBOX"
fi
exec "$BIN" "$@"
`;
}

// fuse states in the binary's fuse wire: the characters "1" / "0" (@electron/fuses FuseState)
const FUSE_ENABLED = 49;
const FUSE_DISABLED = 48;

/** Resolves @electron/fuses the way electron-builder does (it is one of app-builder-lib's dependencies). */
function loadFuses() {
    const builderDir = path.dirname(require.resolve("app-builder-lib/package.json"));
    return require(require.resolve("@electron/fuses", { paths: [builderDir] }));
}

/**
 * electron-builder flips the fuses ("build.electronFuses") after afterPack on "<appOutDir>/<executableName>",
 * which on Linux is the launcher script by then (it would fail: no fuse sentinel in a script). This points that
 * step at the real binary "<executableName>.bin" and reads the fuses back to make sure they were written.
 */
function flipLinuxFusesOnBinary(packager) {
    if (packager.apiTesterFusesOnBin) return;
    if (typeof packager.addElectronFuses !== "function") {
        throw new Error("afterPack: this electron-builder version has no packager.addElectronFuses(); update build/afterPack.js so the Electron fuses reach the .bin");
    }
    const original = packager.addElectronFuses;
    packager.addElectronFuses = async (fuseContext, fuseConfig) => {
        const bin = path.join(fuseContext.appOutDir, `${packager.executableName}.bin`);
        if (!fs.existsSync(bin)) return original.call(packager, fuseContext, fuseConfig);
        const { flipFuses, getCurrentFuseWire } = loadFuses();
        console.log(`  • afterPack: flipping Electron fuses on the real binary ${bin}`);
        await flipFuses(bin, fuseConfig);
        const wire = await getCurrentFuseWire(bin);
        for (const [index, value] of Object.entries(fuseConfig)) {
            if (!/^\d+$/.test(index) || typeof value !== "boolean") continue;
            const expected = value ? FUSE_ENABLED : FUSE_DISABLED;
            if (wire[index] !== expected) throw new Error(`afterPack: fuse ${index} of ${bin} is ${wire[index]}, expected ${expected}`);
        }
        return undefined;
    };
    packager.apiTesterFusesOnBin = true;
}

async function afterPackLinux(context) {
    const appOutDir = context.appOutDir;
    const exeName = context.packager.executableName;
    const exePath = path.join(appOutDir, exeName);
    const binName = `${exeName}.bin`;
    const binPath = path.join(appOutDir, binName);

    // run once per output folder: do not move the script over the binary if the hook runs again
    const head = Buffer.alloc(2);
    const fd = fs.openSync(exePath, "r");
    try { fs.readSync(fd, head, 0, 2, 0); } finally { fs.closeSync(fd); }
    if (head.toString() !== "#!") fs.renameSync(exePath, binPath);
    if (!fs.existsSync(binPath)) throw new Error(`afterPack: Electron binary ${binPath} not found`);

    const asar = fs.existsSync(path.join(appOutDir, "resources", "app.asar"));
    const cliPath = `resources/${asar ? "app.asar" : "app"}/src/cli.js`;
    const productName = context.packager.appInfo.productName;
    fs.writeFileSync(exePath, launcherScript({ binName, cliPath, productName, profileName: exeName }), { mode: 0o755 });
    fs.chmodSync(exePath, 0o755);
    console.log(`  • afterPack: wrote Linux launcher ${exePath} (Electron binary: ${binName})`);
    if (context.packager.config.electronFuses != null) flipLinuxFusesOnBinary(context.packager);
}

/**
 * Electron's and Chromium's licence notices have to ship with the binaries. On Windows and Linux electron-builder
 * keeps them next to the executable; on macOS it copies only Electron.app, so mac.extraResources adds them from
 * node_modules/electron. LICENSES.chromium.html is in node_modules/electron/dist, which exists only once
 * Electron's binary was downloaded (npm start does that): if it is missing, Electron's own installer downloads it
 * (checked against the checksums in the electron package) and the notices are copied here.
 */
function addMacLicenceNotices(resourcesDir) {
    const notices = [["LICENSE.electron.txt", "LICENSE"], ["LICENSES.chromium.html", "LICENSES.chromium.html"]];
    if (notices.every(([name]) => fs.existsSync(path.join(resourcesDir, name)))) return;
    const electronDir = path.dirname(require.resolve("electron/package.json"));
    const distDir = path.join(electronDir, "dist");
    if (!notices.every(([, source]) => fs.existsSync(path.join(distDir, source)))) {
        console.log("  • afterPack: downloading Electron's binary once for its licence notices (node_modules/electron/install.js)");
        const result = spawnSync(process.execPath, [path.join(electronDir, "install.js")], { stdio: "inherit" });
        if (result.status !== 0) throw new Error("afterPack: could not download Electron for its licence notices (node node_modules/electron/install.js)");
    }
    for (const [name, source] of notices) {
        const target = path.join(resourcesDir, name);
        if (fs.existsSync(target)) continue;
        const from = fs.existsSync(path.join(distDir, source)) ? path.join(distDir, source) : path.join(electronDir, source);
        if (!fs.existsSync(from)) throw new Error(`afterPack: licence notice ${source} not found in ${distDir}`);
        fs.copyFileSync(from, target);
    }
    console.log(`  • afterPack: Electron and Chromium licence notices are in ${resourcesDir}`);
}

async function afterPackMac(context) {
    const appName = `${context.packager.appInfo.productFilename}.app`;
    const resourcesDir = path.join(context.appOutDir, appName, "Contents", "Resources");
    addMacLicenceNotices(resourcesDir);
    const wrapper = path.join(resourcesDir, "bin", "api-tester");
    if (!fs.existsSync(wrapper)) {
        console.log(`  • afterPack: CLI wrapper not found at ${wrapper} (check mac.extraResources)`);
        return;
    }
    fs.chmodSync(wrapper, 0o755);
    console.log(`  • afterPack: CLI wrapper ${wrapper} is executable`);
}

async function afterPack(context) {
    if (context.electronPlatformName === "linux") return afterPackLinux(context);
    if (context.electronPlatformName === "darwin" || context.electronPlatformName === "mas") return afterPackMac(context);
    return undefined;
}

