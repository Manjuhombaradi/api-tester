"use strict";
// electron-builder afterPack hook (wired via "afterPack" in package.json "build").
//
// Linux: puts a small POSIX sh launcher in front of the Electron binary: the real binary becomes
// "<executable>.bin" and "<executable>" is the script. The /usr/bin link and the .desktop file of the .deb, the
// AppImage's AppRun and the .tar.gz all start "<executable>", so one script covers all of them.
// Why a script: Chromium decides about its sandbox (and aborts as root) before any app JavaScript runs, so
// main.js cannot fix that. The launcher:
//  - command line use (first argument run / echo-server / help / --help / --version / --cli) or no graphical
//    display: runs src/cli.js with Electron's built-in Node.js (ELECTRON_RUN_AS_NODE), so no Chromium processes
//    (sandbox, zygote, GPU) are started at all - works on servers, in CI and over SSH.
//  - otherwise: starts the desktop app with ELECTRON_DISABLE_SANDBOX=1. The app only loads its own local pages;
//    the sandbox fails as root, under Ubuntu's AppArmor user-namespace restriction, on kernels without user
//    namespaces, and its SUID fallback cannot handle the space in "/opt/API Tester".
//  - checks for missing shared libraries first (minimal server / container images) and prints the exact
//    apt / dnf command instead of a bare "error while loading shared libraries" or SIGTRAP.
// Notes: keep Electron's RunAsNode fuse enabled (the default). electron-builder flips fuses on "<executable>"
// after this hook, so if "electronFuses" is ever configured, flip them on the .bin here.
//
// macOS: makes sure the CLI wrapper Contents/Resources/bin/api-tester is executable.
const fs = require("fs");
const path = require("path");

/** Quotes a value for use inside a double-quoted sh string. */
function shDq(value) {
    return String(value).replace(/[\\"$`]/g, "\\$&");
}

/**
 * Returns the launcher script.
 * binName: file name of the real Electron binary; cliPath: cli.js relative to the app folder;
 * productName: shown in messages.
 */
function launcherScript({ binName, cliPath, productName }) {
    return `#!/bin/sh
# ${productName} launcher, generated by build/afterPack.js. The real Electron binary is ${binName}.
#   api-tester run <suite> ... / echo-server / --help: command line version (Electron's built-in Node.js)
#   no graphical display: command line version as well
#   otherwise: desktop app (Chromium sandbox disabled - it only loads its own local pages)
SELF="$(readlink -f "$0" 2>/dev/null)"
[ -n "$SELF" ] || SELF="$0"
HERE="$(cd "$(dirname "$SELF")" && pwd -P)"
BIN="$HERE/${shDq(binName)}"

# Chromium switches are skipped when looking for the command: the AppImage's AppRun puts --no-sandbox first
is_switch() {
    case "$1" in --no-sandbox|--disable-gpu|--disable-gpu-sandbox|--in-process-gpu|--disable-dev-shm-usage) return 0 ;; esac
    return 1
}
FIRST=""
NARGS=0
for ARG in "$@"; do
    is_switch "$ARG" && continue
    NARGS=$((NARGS + 1))
    if [ -z "$FIRST" ]; then FIRST="$ARG"; fi
done

MODE=gui
case "$FIRST" in
    run|echo-server|help|--help|-h|--version|-v|--cli) MODE=cli ;;
esac
for ARG in "$@"; do
    if [ "$ARG" = "--cli" ]; then MODE=cli; fi
done
if [ "$MODE" = gui ] && [ -z "$DISPLAY" ] && [ -z "$WAYLAND_DISPLAY" ]; then
    if [ "$NARGS" -eq 0 ]; then
        echo "No graphical display found (DISPLAY / WAYLAND_DISPLAY not set) - showing the command line version." >&2
    fi
    MODE=cli
fi
# a local X display that does not exist (stale DISPLAY over SSH, sudo): say so instead of Chromium's errors
if [ "$MODE" = gui ] && [ -z "$WAYLAND_DISPLAY" ]; then
    case "$DISPLAY" in
        :[0-9]*)
            XNUM="\${DISPLAY#:}"
            XNUM="\${XNUM%%.*}"
            if [ ! -S "/tmp/.X11-unix/X$XNUM" ]; then
                echo "Cannot reach the X display $DISPLAY - showing the command line version (use --cli, or fix DISPLAY / X forwarding)." >&2
                MODE=cli
            fi
            ;;
    esac
fi

# true when a shared library can be found; dlopen()ed libraries do not show up in ldd
have_lib() {
    OLD_IFS="$IFS"; IFS=:
    for DIR in $LD_LIBRARY_PATH; do
        if [ -n "$DIR" ] && [ -e "$DIR/$1" ]; then IFS="$OLD_IFS"; return 0; fi
    done
    IFS="$OLD_IFS"
    for DIR in /usr/lib/*-linux-gnu /lib/*-linux-gnu /usr/lib64 /lib64 /usr/lib /lib /usr/local/lib; do
        if [ -e "$DIR/$1" ]; then return 0; fi
    done
    # /sbin is not in a normal user's PATH on Debian
    for LDCONFIG in ldconfig /sbin/ldconfig /usr/sbin/ldconfig; do
        if command -v "$LDCONFIG" >/dev/null 2>&1; then
            "$LDCONFIG" -p 2>/dev/null | grep -q "$1" && return 0
            break
        fi
    done
    return 1
}

# ALSA package name: libasound2t64 on Ubuntu 24.04+ / Debian 13+ (64-bit time_t transition)
alsa_package() {
    if command -v apt-cache >/dev/null 2>&1 && apt-cache show libasound2t64 >/dev/null 2>&1; then
        echo libasound2t64; return
    fi
    ID=""; VERSION_ID=""
    if [ -r /etc/os-release ]; then . /etc/os-release; fi
    case "$ID" in
        ubuntu) if [ "\${VERSION_ID%%.*}" -ge 24 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
        debian) if [ "\${VERSION_ID%%.*}" -ge 13 ] 2>/dev/null; then echo libasound2t64; return; fi ;;
    esac
    echo libasound2
}

# the Electron binary links these libraries even when it only runs as Node.js (command line version)
if command -v ldd >/dev/null 2>&1; then
    MISSING="$(ldd "$BIN" 2>/dev/null | sed -n 's/^[[:space:]]*\\([^[:space:]]*\\) => not found.*/\\1/p' | sort -u | tr '\\n' ' ')"
    if [ "$MODE" = gui ] && ! have_lib libX11-xcb.so.1; then MISSING="\${MISSING}libX11-xcb.so.1 "; fi
    if [ -n "$MISSING" ]; then
        # root (e.g. a minimal container) usually has no sudo
        SUDO="sudo "
        if [ "$(id -u)" = 0 ]; then SUDO=""; fi
        {
            echo "${shDq(productName)} cannot start, these system libraries are missing: $MISSING"
            echo "Install them and start again:"
            echo "  Debian/Ubuntu: \${SUDO}apt-get update && \${SUDO}apt-get install -y libgtk-3-0 libnss3 $(alsa_package) libgbm1 libx11-xcb1 libxss1 libxtst6 libatspi2.0-0 libsecret-1-0 libnotify4 xdg-utils"
            echo "  Fedora/RHEL:   \${SUDO}dnf install -y gtk3 nss alsa-lib mesa-libgbm libX11-xcb libXScrnSaver libXtst at-spi2-core libsecret libnotify xdg-utils"
            echo "Or run suites without the app: the Docker image or Node.js 22.13+ (node src/cli.js run ...)."
        } >&2
        exit 2
    fi
fi

if [ "$MODE" = cli ]; then
    # the command line version does not take Chromium switches
    for ARG in "$@"; do
        shift
        is_switch "$ARG" || set -- "$@" "$ARG"
    done
    export ELECTRON_RUN_AS_NODE=1
    exec "$BIN" "$HERE/${shDq(cliPath)}" "$@"
fi

unset ELECTRON_RUN_AS_NODE
export ELECTRON_DISABLE_SANDBOX=1
exec "$BIN" "$@"
`;
}

async function afterPackLinux(context) {
    const appOutDir = context.appOutDir;
    const exeName = context.packager.executableName;
    const exePath = path.join(appOutDir, exeName);
    const binName = `${exeName}.bin`;
    const binPath = path.join(appOutDir, binName);

    // run once per output folder: do not move the script over the binary if the hook runs again
    const head = Buffer.alloc(2);
    const fd = fs.openSync(exePath, "r");
    try { fs.readSync(fd, head, 0, 2, 0); } finally { fs.closeSync(fd); }
    if (head.toString() !== "#!") fs.renameSync(exePath, binPath);
    if (!fs.existsSync(binPath)) throw new Error(`afterPack: Electron binary ${binPath} not found`);

    const asar = fs.existsSync(path.join(appOutDir, "resources", "app.asar"));
    const cliPath = `resources/${asar ? "app.asar" : "app"}/src/cli.js`;
    const productName = context.packager.appInfo.productName;
    fs.writeFileSync(exePath, launcherScript({ binName, cliPath, productName }), { mode: 0o755 });
    fs.chmodSync(exePath, 0o755);
    console.log(`  • afterPack: wrote Linux launcher ${exePath} (Electron binary: ${binName})`);
}

async function afterPackMac(context) {
    const appName = `${context.packager.appInfo.productFilename}.app`;
    const wrapper = path.join(context.appOutDir, appName, "Contents", "Resources", "bin", "api-tester");
    if (!fs.existsSync(wrapper)) {
        console.log(`  • afterPack: CLI wrapper not found at ${wrapper} (check mac.extraResources)`);
        return;
    }
    fs.chmodSync(wrapper, 0o755);
    console.log(`  • afterPack: CLI wrapper ${wrapper} is executable`);
}

async function afterPack(context) {
    if (context.electronPlatformName === "linux") return afterPackLinux(context);
    if (context.electronPlatformName === "darwin" || context.electronPlatformName === "mas") return afterPackMac(context);
    return undefined;
}

module.exports = afterPack;
module.exports.afterPack = afterPack;
module.exports.launcherScript = launcherScript;
